'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { ready, doc, describe, engine } = require('./helpers');

const NBSP = ' ';

const TEXTS = {
  'новостной': [
    'В среду правительство утвердило план развития городского транспорта до 2030 года. Документ предусматривает строительство трёх новых линий метро, обновление автобусного парка и запуск сети выделенных полос на главных магистралях.',
    'По словам мэра, первые результаты жители увидят уже через два года: к этому сроку откроются восемь станций, а интервалы движения на загруженных маршрутах сократятся вдвое. Финансирование программы составит 480 миллиардов рублей, из которых треть выделит федеральный бюджет.',
    `Эксперты оценивают план сдержанно. «Цифры амбициозные, но без реформы тарифов и честного учёта пассажиропотока они останутся на бумаге»,${NBSP}— считает руководитель центра транспортных исследований Илья Воронов.`,
  ],
  'разговорный': [
    'Привет! Я вчера наконец добралась до той кофейни на Чистых прудах, о которой ты рассказывала. Народу было много, но нам повезло: столик у окна освободился буквально через пять минут.',
    `Кофе, честно говоря, обычный, зато выпечка отличная${NBSP}— возьми миндальный круассан, не пожалеешь. Ещё там продают книги, и я, конечно, не удержалась и купила сборник рассказов, который давно искала.`,
    'Если будешь в центре на выходных, давай сходим вместе? Я свободна в субботу после обеда. Напиши, когда тебе удобно, и я забронирую столик заранее.',
  ],
  'художественный с диалогом': [
    'Дождь шёл с самого утра, и к полудню улица превратилась в мутный ручей. Марина стояла у окна, прижав ладонь к холодному стеклу, и смотрела, как редкие прохожие перебегают от подъезда к подъезду.',
    `— Ты так и будешь стоять?${NBSP}— спросил Андрей, не отрываясь от книги.${NBSP}— Он всё равно не придёт раньше вечера.`,
    `— Знаю,${NBSP}— ответила она, но от окна не отошла. Где-то внизу хлопнула дверь, и по лестнице застучали быстрые шаги; сердце у неё замерло, а потом забилось снова, ровно и устало.`,
    'Андрей отложил книгу. Он давно понял, что спорить бесполезно: когда Марина чего-то ждала, время для неё останавливалось, и никакие разумные доводы не могли сдвинуть стрелки с места.',
  ],
  'деловой': [
    `Коллеги, напоминаю, что отчёт за третий квартал нужно сдать до пятницы. Шаблон лежит в общей папке, там же${NBSP}— инструкция по заполнению. Если у вас возникнут вопросы по цифрам, пишите Ольге: она отвечает за сводную таблицу.`,
    'Отдельно прошу проверить контакты клиентов в базе. В прошлом месяце мы потеряли два заказа из-за неверных адресов, и повторять этот опыт не хочется. Спасибо всем, кто уже обновил данные.',
  ],
};

for (const [name, paras] of Object.entries(TEXTS)) {
  test(`no false positives: ${name}`, async () => {
    await ready();
    const { issues } = engine.check(doc(paras));
    assert.ok(issues.length <= 1, `${issues.length} issues in clean text:\n${describe(issues)}`);
  });
}

test('no false positives: all four texts together give at most 1 issue', async () => {
  await ready();
  const all = Object.values(TEXTS).flat();
  const { issues } = engine.check(doc(all));
  assert.ok(issues.length <= 1, `${issues.length} issues:\n${describe(issues)}`);
});

test('literary: clean texts score high and produce few style signals', async () => {
  await ready();
  const all = Object.values(TEXTS).flat();
  const res = engine.literary(doc(all));
  assert.ok(res.score >= 8, `score ${res.score}`);
  const kanc = res.metrics.find((m) => m.id === 'kanc').count;
  assert.ok(kanc <= 2, `kanc ${kanc}:\n${describe(res.issues)}`);
});

test('proper nouns, abbreviations, latin and numbers are not spelling errors', async () => {
  await ready();
  const { issues } = engine.check(doc([
    'Мы встретились с Ксенией Ромашкиной из компании ЮНЕСКО в офисе на Покровке, обсудили API и релиз 2.0.',
    'Ибрагимов прислал PDF-файл и ссылку на GitHub, а также 3D-модель для печати.',
  ]));
  assert.equal(issues.filter((is) => is.category === 'spelling').length, 0, describe(issues));
});
